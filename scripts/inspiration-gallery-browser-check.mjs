import {chromium} from 'playwright';
const base=process.env.PLOTAO_E2E_URL||'http://127.0.0.1:4173';
const assert=(v,message)=>{if(!v)throw Error(message);};
const browser=await chromium.launch({headless:true});
try {
  const page=await browser.newPage({viewport:{width:1366,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/eshop.html');
  await page.locator('.inspiration-gallery-link a').click();
  await page.locator('.ig-card').first().waitFor();
  assert(await page.locator('.ig-card:visible').count()===15,'Gallery link must show all 15 inspirations');
  await page.locator('.ig-filters [data-gallery-filter="panel"]').click();
  assert(await page.locator('.ig-card:visible').count()===3,'Panel filter must show only panel images');
  assert(new URL(page.url()).searchParams.get('typ')==='panel','Filter must be shareable in URL');
  await page.locator('.ig-card:visible [data-gallery-open]').first().click();
  await page.locator('.ig-lightbox[open]').waitFor();
  const first=await page.locator('#ig-lightbox-image').getAttribute('src');
  await page.keyboard.press('ArrowRight');
  assert(await page.locator('#ig-lightbox-image').getAttribute('src')!==first,'Keyboard must navigate filtered inspirations');
  assert((await page.locator('#ig-lightbox-config').getAttribute('href')).includes('type=panel'),'Configurator must match chosen inspiration');
  await page.keyboard.press('Escape');
  assert(!await page.locator('.ig-lightbox').isVisible(),'Escape must close preview');
  assert(await page.locator('.ig-card:visible [data-gallery-open]').first().evaluate(el=>el===document.activeElement),'Closing preview must restore focus');
  await page.locator('.ig-filters [data-gallery-filter="aluminium"]').click();
  assert(await page.locator('.ig-card:visible').count()===5,'Aluminium filter must show five styles');
  await page.locator('.ig-filters [data-gallery-filter="gabion"]').click();
  await page.reload();
  await page.locator('.ig-card[data-kind="gabion"]').waitFor();
  assert(await page.locator('.ig-card:visible').count()===1,'Selected gallery category must survive reload');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.ig-card:visible [data-gallery-open]').click();
  await page.waitForFunction(()=>{const im=document.querySelector('#ig-lightbox-image');return im.complete&&im.naturalWidth>0;});
  assert(!await page.locator('.ig-next').isVisible(),'Single-image category must hide next and previous arrows');
  assert(await page.locator('.ig-lightbox').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Mobile preview must not overflow');
  await page.keyboard.press('Escape');
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile gallery must not overflow');
  await page.goto(base+'/eshop.html');
  await page.locator('.inspiration-card').filter({has:page.locator('img[alt="Pletivové oplocení"]')}).click();
  await page.locator('.ig-card[data-kind="mesh"]').first().waitFor();
  assert(await page.locator('.ig-card:visible').count()===3,'Existing inspiration thumbnail must open its category gallery');
  assert(!errors.length,'Gallery must not raise JS errors: '+errors.join('; '));
  console.log('PASS inspiration gallery: entry links, five categories, shareable filters, lightbox, keyboard, matching configurator, mobile and images');
} finally {await browser.close();}
