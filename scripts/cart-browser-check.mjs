import {chromium} from 'playwright';
import {validateEnvelope} from '../supabase/functions/submit-lead/validation.mjs';
const base=process.env.PLOTAO_E2E_URL||'http://127.0.0.1:4173';
const assert=(value,message)=>{if(!value)throw Error(message);};
const browser=await chromium.launch({headless:true});
try {
  const context=await browser.newContext({viewport:{width:1366,height:900}});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/komponenty.html');
  await page.waitForFunction(()=>window.PLOTAO_CART_READY===true);
  const contained=await page.locator('.product-card').evaluateAll(cards=>cards.every(card=>{
    const image=card.querySelector('.product-image img').getBoundingClientRect();
    const frame=card.querySelector('.product-image').getBoundingClientRect();
    const info=card.querySelector('.product-info').getBoundingClientRect();
    return image.top>=frame.top-.5&&image.bottom<=frame.bottom+.5&&image.bottom<=info.top+.5;
  }));
  assert(contained,'Desktop product images must stay inside image area and above product text');
  const card=page.locator('.product-card').first();
  await card.locator('.pc-add').click();
  await card.locator('.pc-add').click();
  await page.locator('body>header .header-actions .cart-count').evaluate(el=>el.closest('a').click());
  const dialog=page.locator('.pc-dialog');
  assert(await dialog.isVisible(),'Header must open cart');
  assert(await dialog.locator('.pc-item').count()===1,'Same product must merge');
  assert(await dialog.locator('.pc-item input').inputValue()==='2','Repeated addition must increase quantity');
  await dialog.locator('.pc-item input').fill('0');
  await dialog.locator('.pc-item input').dispatchEvent('change');
  assert(!await dialog.locator('.pc-item input').evaluate(el=>el.checkValidity()),'Zero quantity must be rejected');
  await dialog.locator('.pc-item input').fill('3');
  await dialog.locator('.pc-item input').dispatchEvent('change');
  const total=await dialog.locator('#pc-total').textContent();
  assert(total.includes('567'),'Quantity must update total in cents');
  await page.keyboard.press('Escape');
  assert(!await dialog.isVisible(),'Escape must close cart');
  await page.goto(base+'/eshop-panely.html');
  await page.waitForFunction(()=>window.PLOTAO_CART_READY===true);
  assert(await page.locator('body>header .header-actions .cart-count').textContent()==='3','Cart must persist between pages');
  await page.locator('[data-variant-open]').first().click();
  await page.locator('#variantForm select[name=color]').selectOption('anthracite');
  await page.locator('.pc-variant-add').click();
  await page.goto(base+'/eshop.html#kosik');
  await page.locator('.pc-dialog[open]').waitFor();
  assert(await dialog.locator('.pc-item').count()===2,'Selected variant must survive navigation');
  assert((await dialog.locator('.pc-item').nth(1).textContent()).includes('Antracit'),'Chosen variant must be preserved');
  assert((await dialog.locator('.pc-item').nth(1).textContent()).includes('K nacenění'),'Unpriced variant must not reuse base price');
  await page.setViewportSize({width:390,height:844});
  assert(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Mobile dialog must not overflow horizontally');
  await dialog.locator('[name=name]').fill('Test košíku');
  await dialog.locator('[name=email]').fill('test@example.com');
  await dialog.locator('[name=place]').fill('Uherské Hradiště');
  await dialog.locator('[name=consent]').check();
  // A removed item must not erase contact information already entered.
  await dialog.locator('.pc-remove').nth(1).click();
  assert(await dialog.locator('[name=name]').inputValue()==='Test košíku','Editing cart must preserve contact draft');
  let attempts=0, payload;
  await page.route('**/functions/v1/submit-lead',async route=>{
    attempts++; payload=route.request().postDataJSON();
    const validation=validateEnvelope(payload);
    assert(validation.ok,'Cart payload must satisfy existing server validation: '+JSON.stringify(validation));
    assert(payload.lead.note.includes('Poptávka košíku')&&payload.lead.note.includes('3 ks'),'Submitted payload must include items and quantity');
    await route.fulfill({status:attempts===1?503:200,contentType:'application/json',body:JSON.stringify(attempts===1?{error:'temporary_failure'}:{id:'test-cart-id',email_sent:true})});
  });
  await dialog.locator('button[type=submit]').click();
  await dialog.locator('.pc-status[data-error=true]').waitFor();
  assert(await dialog.locator('.pc-item').count()===1,'Failed send must retain cart');
  assert(await dialog.locator('[name=name]').inputValue()==='Test košíku','Failed send must retain entered contact');
  await dialog.locator('button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('.pc-empty h3')?.textContent==='Poptávku košíku jsme přijali');
  assert(attempts===2,'Retry must send once per submission');
  assert(await page.evaluate(()=>JSON.parse(localStorage.getItem('plotao.cart.v1')).length)===0,'Successful send must clear submitted items');
  await page.keyboard.press('Escape');
  const mobile=page.locator('body>header .pc-mobile-cart');
  assert(await mobile.isVisible(),'Cart must be accessible from mobile header');
  await mobile.click();
  assert((await dialog.locator('.pc-empty').textContent()).includes('prázdný'),'Empty cart state must be visible');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>localStorage.setItem('plotao.cart.v1','{"broken":true}'));
  await page.reload();
  await page.waitForFunction(()=>window.PLOTAO_CART_READY===true);
  assert(await page.locator('body>header .header-actions .cart-count').textContent()==='0','Invalid stored data must recover safely');
  assert(!errors.length,'No browser errors: '+errors.join('; '));
  await context.close();
  console.log('PASS cart: persistence, variants, exact totals, validation, mobile, server payload, failed send, retry, success and empty state');
} finally {await browser.close();}
